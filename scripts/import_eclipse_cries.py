"""Import base-species cries from the same pinned RHH source as the roster.
Retain original Gen I-III samples; store one shared sample for both playback directions.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import hashlib, json, re, time, urllib.request, wave
ROOT = Path(__file__).resolve().parents[1]
SHA = '7b4344c7ee867c98c8fb9d6026791df4f8eaecf7'
BASE = f'https://raw.githubusercontent.com/rh-hideout/pokeemerald-expansion/{SHA}/'
CACHE = ROOT / '.local-tools/roster'
def fetch(path):
    target = CACHE / path
    if not target.exists():
        target.parent.mkdir(parents=True, exist_ok=True)
        for attempt in range(4):
            try:
                data = urllib.request.urlopen(BASE + path, timeout=60).read()
                target.write_bytes(data)
                break
            except Exception:
                if attempt == 3: raise
                time.sleep(attempt + 1)
    return target.read_bytes()
def normalized(value):
    return value.replace('_', '').lower()
def main():
    source = fetch('sound/direct_sound_data.inc').decode()
    labels = {normalized(label): path for label, path in re.findall(
        r'(Cry_\w+)::\s*(?:\.if[^\n]*\n\s*)?\.incbin "([^"]+)"', source)}
    roster = json.loads((ROOT / 'data/eclipse-roster.json').read_text(encoding='utf-8'))['species']
    bodies = json.loads((ROOT / 'data/eclipse-roster-source.json').read_text(encoding='utf-8'))
    rows = []
    for mon in roster:
        cry = re.search(r'\.cryId\s*=\s*(CRY_\w+)', bodies[str(mon['national'])]['body'])[1]
        path = labels[normalized(cry)].replace('.bin', '.wav')
        rows.append(dict(national=mon['national'], id=mon['id'], token=mon['token'], source_path=path))
    assert len(rows) == 639 and rows[0]['id'] == 440 and rows[-1]['id'] == 1078
    # Finizen and Palafin share a source sample; fetch/write each path once.
    paths = sorted({row['source_path'] for row in rows})
    with ThreadPoolExecutor(max_workers=12) as pool:
        downloads = dict(zip(paths, pool.map(fetch, paths)))
    for path, data in downloads.items():
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    def describe(row):
        data = downloads[row['source_path']]
        target = ROOT / row['source_path']
        with wave.open(str(target), 'rb') as sample:
            assert sample.getnchannels() == 1 and sample.getsampwidth() in (1, 2)
            assert sample.getnframes() > 0
            row.update(rate=sample.getframerate(), frames=sample.getnframes(), sha256=hashlib.sha256(data).hexdigest())
        return row
    rows = list(map(describe, rows))
    waves = ['@ Generated by scripts/import_eclipse_cries.py; pinned RHH base-species cries.', '\t.section eclipse_cry_data, "a", %progbits']
    normal = ['\t.align 2', 'gEclipseCryTable::']
    reverse = ['\t.align 2', 'gEclipseCryTable_Reverse::']
    for row in rows:
        label = f"Cry_Eclipse_{row['national']}"
        waves += ['\t.align 2', label + '::', f'\t.incbin "{row["source_path"].replace(".wav", ".bin")}"']
        normal.append('\tcry ' + label)
        reverse.append('\tcry_reverse ' + label)
    waves.append('\t.section .rodata')
    for name, lines in [('eclipse_cry_samples.inc', waves), ('eclipse_cry_tables.inc', normal + reverse)]:
        (ROOT / 'sound' / name).write_bytes(('\n'.join(lines) + '\n').encode())
    (ROOT / 'data/eclipse-cries.json').write_bytes((json.dumps(dict(source=BASE, commit=SHA, species=rows), indent=2) + '\n').encode())
    print(f'Imported {len(rows)} cries, {sum(row["frames"] for row in rows):,} PCM frames.')
if __name__ == '__main__': main()
