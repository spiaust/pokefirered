"""Add now-supported cached Gen IX lessons without replacing existing projections.
No network/art import; outputs remain UTF-8/LF and native reminder-safe.
"""
import json, re
from pathlib import Path
from eclipse_lessons import CAMPAIGN_LESSONS
ROOT=Path(__file__).resolve().parents[1]
def refresh():
    meta_path=ROOT/'data/eclipse-roster.json'
    meta=json.loads(meta_path.read_text(encoding='utf-8'))
    sources=json.loads((ROOT/'data/eclipse-roster-source.json').read_text(encoding='utf-8'))
    text=(ROOT/'.local-tools/roster/src/data/pokemon/level_up_learnsets/gen_9.h').read_text(encoding='utf-8')
    learn={name:re.findall(r'LEVEL_UP_MOVE\(\s*(\d+),\s*(MOVE_\w+)\)',body) for name,body in re.findall(r'\b(s\w+LevelUpLearnset)\[\]\s*=\s*\{(.*?)\};',text,re.S)}
    native=set(re.findall(r'#define (MOVE_\w+)\s+\d+', (ROOT/'include/constants/moves.h').read_text(encoding='utf-8')))
    added=changed=0;lines=[]
    for row in meta['species']:
        match=re.search(r'\.levelUpLearnset\s*=\s*(\w+)',sources[str(row['national'])]['body'])
        assert match and match[1] in learn,row['name']
        previous=[list(x) for x in row['moves']];values=list(previous)
        for level,move in learn[match[1]]:
            pair=[max(1,int(level)),move]
            if move in native and pair not in values:values.append(pair)
        for level,move in CAMPAIGN_LESSONS.get(row['national'],[]):
            pair=[level,move]
            if move in native and pair not in values:values.append(pair)
        values.sort(key=lambda x:x[0])
        assert len(values)<=24,(row['name'],len(values))
        assert all(pair in values for pair in previous)
        added+=len(values)-len(previous);changed+=values!=previous;row['moves']=values
        lines.append('static const u16 sEclipseLearn'+str(row['national'])+'[] = {'+', '.join('LEVEL_UP_MOVE('+str(level)+', '+move+')' for level,move in values)+', LEVEL_UP_END};')
    meta_path.write_bytes((json.dumps(meta,ensure_ascii=False,indent=2)+'\n').encode('utf-8'))
    (ROOT/'src/data/eclipse_roster/learnsets.h').write_bytes(('// Generated by scripts/import_eclipse_roster.py; do not edit.\n'+'\n'.join(lines)+'\n').encode('utf-8'))
    print('Added',added,'lessons across',changed,'species; max',max(len(r['moves']) for r in meta['species']))
if __name__=='__main__':refresh()
